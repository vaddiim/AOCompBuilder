<#
.SYNOPSIS
  Downloads the item and spell icons the catalog needs into assets/icons/{items,spells}.
.DESCRIPTION
  Reads assets/data/catalog.json (generated by the app on first run), so run the app or
  `cargo test` once first. Idempotent: files already on disk are skipped. Each download is
  retried with a growing delay, written to a .part file and renamed, so an interrupted run
  never leaves a truncated PNG. Failures are listed in the report file and the exit code is 1.
  Item enchants @1..@4 are fetched for enchantable slots only (see Slot::enchantable in
  src/catalog.rs); on disk they are named `<id>_e<n>.png`, as src/app.rs expects.
.PARAMETER Retries    Attempts per file (default 4).
.PARAMETER Size       Icon size in pixels (default 64: about 14 MB for the T8 catalog, against 150 MB at the 217 px default).
.PARAMETER Throttle   Parallel downloads (default 8).
.PARAMETER Report     Where failed downloads are written (default: icons-failed.txt in the project root).
.PARAMETER DryRun    Only count what is missing; download and write nothing.
#>
[CmdletBinding()]
param(
    [int]$Retries = 4,
    [int]$Throttle = 8,
    [int]$Size = 64,
    [string]$Report,
    [switch]$DryRun
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $Report) { $Report = Join-Path $root 'icons-failed.txt' }
$catalogPath = Join-Path $root 'assets/data/catalog.json'
if (-not (Test-Path $catalogPath)) { throw "$catalogPath not found: run the app or 'cargo test' once to build it." }
$catalog = Get-Content $catalogPath -Raw -Encoding utf8 | ConvertFrom-Json

$noEnchant = 'Mount', 'Food', 'Potion'
$jobs = [System.Collections.Generic.List[object]]::new()
foreach ($item in $catalog.items) {
    # `icon` is the id the renderer knows the item by (Item.icon in src/catalog.rs).
    $base = if ($item.icon) { $item.icon } else { $item.id }
    $levels = if ($noEnchant -contains $item.slot) { 0 } else { 0..4 }
    foreach ($e in $levels) {
        $remote = if ($e -gt 0) { "$base@$e" } else { $base }
        $local = if ($e -gt 0) { "${base}_e$e" } else { $base }
        $jobs.Add([pscustomobject]@{
            Kind = 'item'; Names = @($remote)
            Path = Join-Path $root "assets/icons/items/$local.png"
        })
    }
}
# Some `uisprite` names do not exist on the render service; the spell's own id is the fallback.
foreach ($group in $catalog.spells.PSObject.Properties.Value | Group-Object icon) {
    $icon = $group.Name
    $jobs.Add([pscustomobject]@{
        Kind = 'spell'; Names = @($icon) + @($group.Group.id | Where-Object { $_ -ne $icon })
        Path = Join-Path $root "assets/icons/spells/$icon.png"
    })
}

$jobs = [System.Collections.Generic.List[object]]@($jobs | Sort-Object Path -Unique)
$todo = @($jobs | Where-Object { -not (Test-Path $_.Path) -or (Get-Item $_.Path).Length -eq 0 })
Write-Host "$($jobs.Count) icons wanted, $($jobs.Count - $todo.Count) already present, $($todo.Count) to download."
if ($DryRun) {
    $todo | Select-Object -First 5 | ForEach-Object { Write-Host "  e.g. $($_.Kind) $($_.Names -join '|') -> $($_.Path)" }
    return
}
if ($todo.Count -eq 0) { if (Test-Path $Report) { Remove-Item $Report }; return }

foreach ($dir in 'assets/icons/items', 'assets/icons/spells') {
    New-Item -ItemType Directory -Force (Join-Path $root $dir) | Out-Null
}

$failed = $todo | ForEach-Object -ThrottleLimit $Throttle -Parallel {
    $job = $_
    $part = "$($job.Path).part"
    $last = ''
    foreach ($name in $job.Names) {
        $url = "https://render.albiononline.com/v1/$($job.Kind)/$([uri]::EscapeDataString($name)).png?size=$($using:Size)"
        for ($try = 1; $try -le $using:Retries; $try++) {
            try {
                Invoke-WebRequest -Uri $url -OutFile $part -TimeoutSec 30
                if ((Get-Item $part).Length -eq 0) { throw 'empty response' }
                Move-Item $part $job.Path -Force
                return
            } catch {
                Remove-Item $part -ErrorAction SilentlyContinue
                $status = $_.Exception.Response.StatusCode.value__
                $last = [string]($status ?? $_.Exception.Message)
                # A 404 means the renderer has no such icon; retrying will not help.
                if ($status -eq 404) { break }
                Start-Sleep -Seconds (2 * $try)
            }
        }
    }
    "$($job.Kind) $($job.Names -join '|') ($last)"
}

if ($failed) {
    $failed | Set-Content $Report -Encoding utf8
    Write-Warning "$(@($failed).Count) downloads failed, listed in $Report. Re-run to retry."
    exit 1
}
if (Test-Path $Report) { Remove-Item $Report }
Write-Host 'Done.'
